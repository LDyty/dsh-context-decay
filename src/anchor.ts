/**
 * Anchor presentation, parsing, and the deterministic anchor pool.
 *
 * The model sees `⟦#a8c5⟧`: a four-character lowercase alphanumeric handle.
 * Anchors are presentation, not content. The pool is deterministic for a
 * session: a SHA-256 stream seeded by the durable session id generates
 * candidates, while recycled anchors are reused before new ones are taken.
 * This keeps replay and projection checkpoints stable without writing anchors
 * into the session log.
 *
 * 中文：锚点展示、解析与确定性锚点池。
 * 模型看到 `⟦#a8c5⟧`：4 位小写英文数字句柄。锚点只是展示，不属于内容。
 * 锚点池按会话确定性生成：以持久 session id 为种子的 SHA-256 流产生候选，
 * 被压缩释放的锚点优先复用，不够时再扩池。这样重放和 projection checkpoint
 * 都不需要把锚点写进 session 日志。
 */

import { createHash } from 'node:crypto'

const OPEN = '⟦#'
const CLOSE = '⟧'
const CHARS = '0123456789abcdefghijklmnopqrstuvwxyz'
const LENGTH = 4
const SPACE = CHARS.length ** LENGTH
const ANCHOR = /^[a-z0-9]{4}$/
const TOKEN = /⟦#([a-z0-9]{4})⟧/i
const LEADING_TOKENS = /^(?:\s*⟦#[a-z0-9]{4}⟧)+\s*/i
const ALL_TOKENS = /⟦#[a-z0-9]{4}⟧/gi
const ANCHOR_ARGUMENT = /^\s*(?:⟦#([a-z0-9]{4})⟧|#([a-z0-9]{4})|([a-z0-9]{4}))\s*$/i

/**
 * Initial number of pre-generated anchors; refill target after low water.
 * 中文：初始预生成锚点数量；低水位后的扩池目标。
 */
export const ANCHOR_POOL_INITIAL = 64

/**
 * Refill the pool when fewer than this many anchors are available.
 * 中文：可用锚点少于该数量时扩池。
 */
export const ANCHOR_POOL_LOW_WATER = 16

/**
 * Number of anchors generated by one refill.
 * 中文：一次扩池生成的锚点数量。
 */
export const ANCHOR_POOL_REFILL = 64

/**
 * Seed used when no durable session id is available (tests, one-shot folds).
 * 中文：没有持久 session id 时使用的种子（测试和一次性 fold）。
 */
export const DEFAULT_ANCHOR_SEED = 'dsh-context-decay/default-anchor-seed'

/**
 * Format one model-visible anchor.
 * 中文：格式化一个模型可见锚点。
 */
export function formatAnchor(anchor: string): string {
  return `${OPEN}${anchor}${CLOSE}`
}

/**
 * Read the first anchor from a text, or null when it has none.
 * 中文：从文本中读取第一个锚点；没有则返回 null。
 */
export function parseAnchor(text: string): string | null {
  const match = TOKEN.exec(text)
  return match === null ? null : match[1]!.toLowerCase()
}

/**
 * Parse one tool `from`/`to` argument into an anchor handle.
 *
 * Accepts the visible form (`⟦#a8c5⟧`), the bare form (`#a8c5`), or the raw
 * four-character handle (`a8c5`). Returns null for anything else.
 *
 * 中文：把一个工具 `from`/`to` 参数解析成锚点句柄。
 * 接受可见形式（`⟦#a8c5⟧`）、裸形式（`#a8c5`）或裸 4 位句柄（`a8c5`）；
 * 其他值返回 null。
 */
export function parseAnchorArgument(value: unknown): string | null {
  if (typeof value !== 'string') return null
  const match = ANCHOR_ARGUMENT.exec(value)
  if (match === null) return null
  return (match[1] ?? match[2] ?? match[3]!).toLowerCase()
}

/**
 * Parse a `to`-style bound: an anchor argument or the literal `end`.
 * 中文：解析 `to` 边界：锚点参数或字面量 `end`。
 */
export function parseAnchorBound(value: unknown): string | 'end' | null {
  if (value === 'end') return 'end'
  return parseAnchorArgument(value)
}

/**
 * Remove a leading run of copied anchors from an assistant message.
 * 中文：去掉 assistant 消息开头连续复制的锚点。
 */
export function stripLeadingAnchors(text: string): string {
  return text.replace(LEADING_TOKENS, '')
}

/**
 * Remove every anchor token from a summary; the summary must not bake one in.
 * 中文：从摘要中移除所有锚点；摘要里不能写入锚点。
 */
export function stripAnchors(text: string): string {
  return text.replace(ALL_TOKENS, ' ').replace(/[ \t]+/g, ' ').trim()
}

/**
 * Whether a raw handle has the expected four lowercase alphanumeric characters.
 * 中文：裸句柄是否是期望的 4 位小写英文数字。
 */
export function isAnchor(anchor: string): boolean {
  return ANCHOR.test(anchor)
}

/**
 * Derive the deterministic pool seed from a durable session id.
 * 中文：从持久 session id 推导确定性锚点池种子。
 */
export function anchorSeedOf(sessionId: string | undefined): string {
  return sessionId === undefined || sessionId.length === 0 ? DEFAULT_ANCHOR_SEED : sessionId
}

/**
 * Generate the candidate at `counter` from a seed.
 *
 * One SHA-256 digest is reduced to a base-36 number of exactly four
 * characters. Collisions are resolved by the caller, which advances the
 * counter and checks the issued set.
 *
 * 中文：从种子生成第 `counter` 个候选。
 * 一个 SHA-256 摘要约简为恰好 4 位的 36 进制数。冲突由调用方处理：递增计数器并检查
 * 已发放集合。
 */
export function generateAnchor(seed: string, counter: number): string {
  const digest = createHash('sha256').update(`${seed}:${counter}`).digest()
  let value = digest.readUInt32BE(0) % SPACE
  let anchor = ''
  for (let index = 0; index < LENGTH; index += 1) {
    anchor = CHARS[value % CHARS.length]! + anchor
    value = Math.floor(value / CHARS.length)
  }
  return anchor
}

/**
 * Pick the first unused candidate, advancing the counter through collisions.
 * 中文：挑选第一个未使用的候选；冲突时递增计数器继续找。
 */
export function nextUnusedAnchor(seed: string, counter: number, used: ReadonlySet<string>): {
  anchor: string
  counter: number
} {
  let cursor = counter
  for (let attempt = 0; attempt < SPACE; attempt += 1) {
    const anchor = generateAnchor(seed, cursor)
    cursor += 1
    if (!used.has(anchor)) return { anchor, counter: cursor }
  }
  throw new Error('context-decay：锚点池已用尽（所有四字符句柄都生成过了）')
}
